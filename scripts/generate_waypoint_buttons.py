"""Generate the twelve east and west waypoint slots for each map size."""
from pathlib import Path

WORLD = Path(__file__).resolve().parents[1] / "data/yrh.map/function/function/worldmap/waypoint/layout"
MOVE = WORLD.parent / "move_layout"

PALETTE = (
    ("magenta", 0xC74EBD), ("pink", 0xF38BAA), ("red", 0xB02E26),
    ("brown", 0x835432), ("orange", 0xF9801D), ("yellow", 0xFED83D),
    ("lime", 0x80C71F), ("green", 0x5E7C16), ("cyan", 0x169C9C),
    ("light_blue", 0x3AB3DA), ("blue", 0x3C44AA), ("purple", 0x8932B8),
)
MAP_SCORE = "scores={yrh_map_id=$(map_id)}"


def default_pin_item(slot):
    color, tint = PALETTE[slot - 1]
    return (
        f'{{id:"minecraft:{color}_stained_glass",count:1,components:'
        f'{{"minecraft:item_model":"yrh.map:waypoint","minecraft:dyed_color":{tint}}}}}'
    )


def button(x, z, label, action, width, extra="", label_tag="", color="white", scale=0.48):
    tags = f'"yrh.map.pan_control","yrh.map.new_part","yrh.map.waypoint_part","yrh.map.pan_control.{action}"'
    display_tags = '"yrh.map.pan_label","yrh.map.new_part","yrh.map.waypoint_part"' + label_tag
    # These vanilla glyphs have 7 px of ink and 1 px of trailing advance.
    # The one-line text display offsets the ink center by (+0.5, -5.5) px on the map.
    label_x = -0.5 * 0.025 * scale
    label_z = 5.5 * 0.025 * scale
    return [
        f'summon minecraft:interaction ~{x:g} ~1.005 ~{z:g} {{Tags:[{tags}],width:{width:g}f,height:0.10f,response:1b{extra}}}',
        f'summon minecraft:text_display ~{x:g} ~1.035 ~{z:g} {{Tags:[{display_tags}],text:{{text:"{label}",color:"{color}",shadow_color:0}},'
        'background:0,default_background:0b,shadow:0b,billboard:"fixed",brightness:{block:15,sky:15},Rotation:[0f,0f],'
        f'transformation:{{translation:[{label_x:g}f,0f,{label_z:g}f],right_rotation:[0f,0f,0f,1f],'
        'left_rotation:[-0.7071068f,0f,0f,0.7071068f],'
        f'scale:[{scale:g}f,{scale:g}f,{scale:g}f]}}}}',
    ]


def appearance_button(x, z, slot, width):
    return [
        f'summon minecraft:interaction ~{x:g} ~1.005 ~{z:g} '
        f'{{Tags:["yrh.map.pan_control","yrh.map.new_part","yrh.map.waypoint_part",'
        f'"yrh.map.pan_control.waypoint_appearance"],width:{width:g}f,height:0.10f,'
        f'response:1b,data:{{yrhmap:{{WaypointSlot:{slot}}}}}}}',
        f'summon minecraft:item_display ~{x:g} ~1.045 ~{z:g} '
        f'{{Tags:["yrh.map.new_part","yrh.map.waypoint_part","yrh.map.waypoint_preview.{slot}"],'
        f'item:{default_pin_item(slot)},item_display:"none",'
        'billboard:"fixed",brightness:{block:15,sky:15},transformation:'
        '{translation:[0f,0f,0f],left_rotation:[0.7071068f,0f,0f,0.7071068f],right_rotation:[0f,0f,1f,0f],'
        'scale:[0.29f,0.29f,0.08f]}}',
    ]


def move_button(slot, action, display_type, display_tag, x, z, width):
    interaction = (
        f'@e[type=minecraft:interaction,tag=yrh.map.pan_control.{action},{MAP_SCORE},'
        f'nbt={{data:{{yrhmap:{{WaypointSlot:{slot}}}}}}},limit=1]'
    )
    display = f'@e[type=minecraft:{display_type},tag=yrh.map.{display_tag}.{slot},{MAP_SCORE},limit=1]'
    y = 1.035 if display_type == "text_display" else 1.045
    return [
        f'$execute as {interaction} positioned ~{x:g} ~1.005 ~{z:g} run '
        f'function yrh.map:function/worldmap/waypoint/move_hitbox {{width:{width:g}}}',
        f'$tp {display} ~{x:g} ~{y:g} ~{z:g}',
    ]


MOVE.mkdir(parents=True, exist_ok=True)
for size in (3, 5, 7, 9, 11, 13):
    lines = ["# Generated by scripts/generate_waypoint_buttons.py"]
    moves = ["# Generated by scripts/generate_waypoint_buttons.py"]
    for side, offset in ((-1, 0), (1, 6)):
        for row in range(6):
            slot = offset + row + 1
            strip_center = side * (size / 2 + .50)
            x = strip_center - side * .25
            delete_x = strip_center + side * .15
            z = -.5 + (row - 2.5) * size / 6
            width = min(.40, size / 12 - .045)
            # Pull both controls toward the row center while keeping their hitboxes apart.
            offset_z = max(min(.24, size / 24) * .75, (width + .01) / 2)
            extra = f',data:{{yrhmap:{{WaypointSlot:{slot}}}}}'
            lines.extend(button(x, z + offset_z, f"P{slot}", "waypoint", width, extra,
                                label_tag=f',"yrh.map.waypoint_slot.{slot}"'))
            lines.extend(appearance_button(x, z - offset_z, slot, width))
            lines.extend(button(delete_x, z, "✘", "waypoint_delete", width, extra,
                                label_tag=f',"yrh.map.waypoint_delete_label.{slot}"', color="red", scale=1.6))
            moves.extend(move_button(slot, "waypoint", "text_display", "waypoint_slot", x, z + offset_z, width))
            moves.extend(move_button(slot, "waypoint_appearance", "item_display", "waypoint_preview", x, z - offset_z, width))
            moves.extend(move_button(slot, "waypoint_delete", "text_display", "waypoint_delete_label", delete_x, z, width))
    (WORLD / f"{size}.mcfunction").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (MOVE / f"{size}.mcfunction").write_text("\n".join(moves) + "\n", encoding="utf-8")

(WORLD.parent / "appearance").mkdir(parents=True, exist_ok=True)
(WORLD.parent / "appearance" / "initialize_palette.mcfunction").write_text(
    "data modify storage yrh.map:_ worldmap.waypoint_palette set value {"
    + ",".join(f's{slot}:{default_pin_item(slot)}' for slot in range(1, len(PALETTE) + 1))
    + "}\n",
    encoding="utf-8",
)
