"""Generate the sonar radius effects and matching angle thresholds."""

import json
from math import radians, tan
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "resource_pack_overlay/assets/yrh.map/post_effect/radial_cursor"
QUANTIZE = ROOT / "data/yrh.map/function/ui/radial_menu/quantize_cursor.mcfunction"
SEARCH = QUANTIZE.parent / "cursor_search"
STOP_POINTS = ((0, 0.018), (2, 0.045), (4, 0.095), (7, 0.137),
               (15, 0.163), (30, 0.219), (70, 0.46))
STEPS_PER_RANGE = 16
FADE_START = 45
FADE_END = STOP_POINTS[-1][0]


def radius_steps():
    for (start_angle, start_radius), (end_angle, end_radius) in zip(STOP_POINTS, STOP_POINTS[1:]):
        for step in range(STEPS_PER_RANGE):
            fraction = step / STEPS_PER_RANGE
            angle = start_angle + fraction * (end_angle - start_angle)
            radius = start_radius + fraction * (end_radius - start_radius)
            yield angle, round(radius, 6)


def threshold_for_angle(angle):
    # Keep the radius change exactly aligned with the selection threshold.
    return 60300 if angle == 7 else round((2000 * tan(radians(angle))) ** 2)


def opacity_for_angle(angle):
    remaining = max(0.0, min(1.0, (FADE_END - angle) / (FADE_END - FADE_START)))
    return round(remaining * remaining * (3.0 - 2.0 * remaining), 6)


def write_search(steps, start, end, path):
    commands = ["# Generated by scripts/generate_radial_cursor_effects.py"]
    if end - start <= 3:
        for index in range(end - 1, start, -1):
            threshold = threshold_for_angle(steps[index][0])
            commands.append(
                f"execute if score #radial_radius_sq yrh_map_tmp matches {threshold}.. "
                f"run return run scoreboard players set #radial_cursor_next yrh_map_tmp {index}"
            )
        commands.append(f"scoreboard players set #radial_cursor_next yrh_map_tmp {start}")
    else:
        middle = (start + end) // 2
        threshold = threshold_for_angle(steps[middle][0])
        namespace = "yrh.map:ui/radial_menu/cursor_search"
        left = f"{start}_{middle - 1}"
        right = f"{middle}_{end - 1}"
        commands.append(
            f"execute if score #radial_radius_sq yrh_map_tmp matches {threshold}.. "
            f"run return run function {namespace}/{right}"
        )
        commands.append(f"return run function {namespace}/{left}")
        write_search(steps, start, middle, SEARCH / f"{left}.mcfunction")
        write_search(steps, middle, end, SEARCH / f"{right}.mcfunction")
    path.write_text("\n".join(commands) + "\n", encoding="utf-8")


def generate():
    DEST.mkdir(parents=True, exist_ok=True)
    SEARCH.mkdir(parents=True, exist_ok=True)
    steps = list(radius_steps())
    write_search(steps, 0, len(steps), QUANTIZE)
    for index, (angle, radius) in enumerate(steps):
        effect = {
            "targets": {"swap": {}},
            "passes": [{
                "vertex_shader": "minecraft:core/screenquad",
                "fragment_shader": "yrh.map:post/radial_cursor",
                "inputs": [{"sampler_name": "In", "target": "minecraft:main"}],
                "output": "swap",
                "uniforms": {
                    "CursorConfig": [
                        {"name": "Radius", "type": "float", "value": radius},
                        {"name": "Opacity", "type": "float", "value": opacity_for_angle(angle)},
                    ],
                },
            }, {
                "vertex_shader": "minecraft:core/screenquad",
                "fragment_shader": "minecraft:post/blit",
                "inputs": [{"sampler_name": "In", "target": "swap"}],
                "output": "minecraft:main",
                "uniforms": {
                    "BlitConfig": [{"name": "ColorModulate", "type": "vec4", "value": [1, 1, 1, 1]}],
                },
            }],
        }
        (DEST / f"{index}.json").write_text(
            json.dumps(effect, separators=(",", ":")) + "\n", encoding="utf-8",
        )


if __name__ == "__main__":
    generate()
