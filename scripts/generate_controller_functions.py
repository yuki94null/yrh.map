"""Generate controller creation and relocation from the same button layout."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "data/yrh.map/function/function/worldmap/controller"
BUTTONS = [
    ("size", "SIZE", -1.2, -1.2),
    ("north", "↑", 0, -1.2),
    ("scale", "SCALE", 1.2, -1.2),
    ("west", "←", -1.2, 0),
    ("home", "🏠", 0, 0),
    ("east", "→", 1.2, 0),
    ("pin", "PIN", -1.2, 1.2),
    ("south", "↓", 0, 1.2),
    ("reload", "↻", 1.2, 1.2),
]


def generate():
    create = ["# Generated by scripts/generate_controller_functions.py"]
    move = ["# Generated by scripts/generate_controller_functions.py; execute at owner X/Z and anchor Y."]
    for action, label, x, z in BUTTONS:
        for kind, y, dz in (("interaction", 1.015, 0), ("text_display", 1.035, 0.08)):
            role = "pan_control" if kind == "interaction" else "pan_label"
            tags = [f"yrh.map.{role}", "yrh.map.foot_controller", "yrh.map.controller_new",
                    f"yrh.map.controller.{action}"]
            if action == "home" and kind == "interaction":
                tags.append("yrh.map.controller.layout_3x3_v4")
            if kind == "interaction":
                tags.append(f"yrh.map.pan_control.{action}")
                props = 'width:0.8f,height:0.35f,response:1b'
            else:
                color = "white"
                props = (f'text:{{text:"{label}",color:"{color}",shadow_color:0}},billboard:"fixed",teleport_duration:2,brightness:{{block:15,sky:15}},'
                         'transformation:{translation:[0f,0f,0f],left_rotation:[-0.7071068f,0f,0f,0.7071068f],'
                         'right_rotation:[0f,0f,0f,1f],scale:[0.7f,0.7f,0.7f]},background:1073741824,see_through:0b')
            pos = f"~{x:g} ~{y:g} ~{z + dz:g}"
            tag_list = ",".join(f'"{tag}"' for tag in tags)
            create.append(f'summon minecraft:{kind} {pos} {{Tags:[{tag_list}],{props}}}')
            move.append(f'$tp @e[type=minecraft:{kind},tag=yrh.map.foot_controller,tag=yrh.map.controller.{action},scores={{yrh_map_id=$(map_id)}}] {pos}')
    move.append("return 1")
    for name, lines in (("create_controller_buttons", create), ("move_controller", move)):
        (DEST / f"{name}.mcfunction").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate()
