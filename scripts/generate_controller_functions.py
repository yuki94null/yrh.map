"""Generate controller creation and relocation from the same button layout."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEST = ROOT / "data/yrh.map/function/function/worldmap/controller"
ROWS = [
    [("size", "5×5"), None, ("scale", "1:16")],
    [("reload", "\ue205\ue208"), ("pan", "\ue206\ue209"), ("home", "\ue207\ue20a")],
]
COLUMN_STEP = 0.78
ROW_STEP = 0.58
FOOT_ROW = 1
ICON_ACTIONS = {"reload", "pan", "home"}


def generate():
    create = ["# Generated by scripts/generate_controller_functions.py"]
    move = ["# Generated by scripts/generate_controller_functions.py; execute at owner X/Z and anchor Y."]
    buttons = ((*entry, (column - 1) * COLUMN_STEP, (row - FOOT_ROW) * ROW_STEP)
               for row, entries in enumerate(ROWS)
               for column, entry in enumerate(entries) if entry is not None)
    for action, label, x, z in buttons:
        is_icon = action in ICON_ACTIONS
        icon_font = ',font:"yrh.map:controller_button"' if is_icon else ""
        for kind, role, y, dz in (
            ("interaction", "pan_control", 1.015, 0),
            ("text_display", "pan_label", 1.035, 0 if is_icon else 0.08),
            ("text_display", "controller_background", 1.025, 0),
        ):
            tags = [f"yrh.map.{role}", "yrh.map.foot_controller", "yrh.map.controller_new",
                    f"yrh.map.controller.{action}"]
            if action == "pan" and kind == "interaction":
                tags.append("yrh.map.controller.layout_v20")
            if kind == "interaction":
                width = 0.72 if action == "pan" else 0.50
                props = f'width:{width:.2f}f,height:0.09f,response:1b'
                tags.append(f"yrh.map.pan_control.{action}")
            elif role == "pan_label":
                props = (f'text:{{text:"{label}",color:"white",shadow_color:0{icon_font}}},billboard:"fixed",teleport_duration:2,brightness:{{block:15,sky:15}},'
                         'transformation:{translation:[0f,0f,0f],left_rotation:[-0.7071068f,0f,0f,0.7071068f],'
                         'right_rotation:[0f,0f,0f,1f],scale:[0.56f,0.56f,0.56f]},'
                         'background:0,default_background:0b,see_through:0b')
            else:
                props = (
                    'text:{text:"\ue203\ue204",font:"yrh.map:controller_button",color:"white",shadow_color:0},'
                    'line_width:64,alignment:"center",billboard:"fixed",teleport_duration:2,'
                    'brightness:{block:15,sky:15},text_opacity:255,background:0,default_background:0b,'
                    'shadow:0b,see_through:0b,transformation:{translation:[0f,0f,0f],'
                    'left_rotation:[-0.7071068f,0f,0f,0.7071068f],right_rotation:[0f,0f,0f,1f],'
                    'scale:[0.9f,0.65f,1f]}'
                )
            pos = f"~{x:g} ~{y:g} ~{z + dz:g}"
            tag_list = ",".join(f'"{tag}"' for tag in tags)
            create.append(f'summon minecraft:{kind} {pos} {{Tags:[{tag_list}],{props}}}')
            move.append(f'$tp @e[type=minecraft:{kind},tag=yrh.map.foot_controller,tag=yrh.map.{role},tag=yrh.map.controller.{action},scores={{yrh_map_id=$(map_id)}}] {pos}')
    move.append("return 1")
    for name, lines in (("create_controller_buttons", create), ("move_controller", move)):
        (DEST / f"{name}.mcfunction").write_text("\n".join(lines) + "\n", encoding="utf-8")


if __name__ == "__main__":
    generate()
