"""Generate walkable support grids from 26.3 Happy Ghast dimensions."""
from pathlib import Path

PLATFORM = Path(__file__).resolve().parents[1] / "data/yrh.map/function/function/worldmap/platform"
SIZES = (3, 5, 7, 9, 11, 13)
MAX_WIDTH = 4
TOP = .98
(PLATFORM / "layout").mkdir(parents=True, exist_ok=True)

for size in SIZES:
    rows = (size + MAX_WIDTH - 1) // MAX_WIDTH
    width = size / rows
    scale = width / MAX_WIDTH
    bottom = TOP - width
    lines = ["# Generated by scripts/generate_map_platforms.py"]
    for row in range(rows):
        for column in range(rows):
            x = -size / 2 + (column + .5) * width
            z = -.5 - size / 2 + (row + .5) * width
            lines.append(
                f"function yrh.map:function/worldmap/platform/summon_at "
                f"{{x:{x:.8f},y:{bottom:.8f},z:{z:.8f},scale:{scale:.8f}}}"
            )
    (PLATFORM / f"layout/{size}.mcfunction").write_text("\n".join(lines) + "\n", encoding="utf-8")
